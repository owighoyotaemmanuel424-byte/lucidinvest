import "server-only";
import { getSql } from "@/lib/db";
import { buildPdf, wrapLine } from "@/lib/pdf";

/**
 * Downloadable reports.
 *
 * Every report is generated from database rows for the signed-in customer or,
 * for administrative reports, for an administrator. CSV and PDF are produced
 * from the same dataset so the two formats cannot disagree.
 */

export const CUSTOMER_REPORTS = [
  { key: "account_statement", label: "Account statement" },
  { key: "investment_statement", label: "Investment statement" },
  { key: "transactions", label: "Transaction report" },
  { key: "deposits", label: "Deposit report" },
  { key: "withdrawals", label: "Withdrawal report" },
  { key: "portfolio_performance", label: "Portfolio performance" },
] as const;

export const ADMIN_REPORTS = [
  { key: "admin_activity", label: "Administrative activity" },
  { key: "compliance", label: "Compliance report" },
] as const;

export type ReportKind = (typeof CUSTOMER_REPORTS)[number]["key"] | (typeof ADMIN_REPORTS)[number]["key"];

type ReportRow = Record<string, string | number | null>;

type Dataset = {
  title: string;
  subtitle: string;
  columns: { key: string; label: string }[];
  rows: ReportRow[];
};

function rows<T>(value: unknown): T[] {
  return Array.isArray(value) ? (value.filter((row) => row && typeof row === "object") as T[]) : [];
}

function csvCell(value: string | number | null | undefined) {
  const text = value === null || value === undefined ? "" : String(value);
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

export function toCsv(dataset: Dataset) {
  const header = dataset.columns.map((column) => csvCell(column.label)).join(",");
  const body = dataset.rows.map((row) => dataset.columns.map((column) => csvCell(row[column.key])).join(","));
  return [header, ...body].join("\n") + "\n";
}

export function datasetToPdf(dataset: Dataset) {
  const widths = dataset.columns.map((column) => {
    const longest = Math.max(
      column.label.length,
      ...dataset.rows.slice(0, 200).map((row) => String(row[column.key] ?? "").length),
    );
    return Math.min(30, Math.max(column.label.length, longest));
  });
  const header = dataset.columns.map((column, index) => column.label.slice(0, widths[index]).padEnd(widths[index])).join("  ");
  const rule = widths.map((width) => "-".repeat(width)).join("  ");
  const lines = [header, rule];
  for (const row of dataset.rows) {
    const line = dataset.columns
      .map((column, index) => String(row[column.key] ?? "").slice(0, widths[index]).padEnd(widths[index]))
      .join("  ");
    lines.push(...wrapLine(line, 112));
  }
  lines.push("", `${dataset.rows.length} row(s). Generated by LucidInvest.`);
  return buildPdf(dataset.title, lines, dataset.subtitle);
}

export async function buildReport(
  actor: { id: string; role: string; full_name: string; email: string },
  kind: string,
  format: string,
): Promise<{ dataset: Dataset; contentType: string; body: Buffer | string; extension: string } | null> {
  const adminKinds = ADMIN_REPORTS.map((report) => report.key);
  const isAdminReport = adminKinds.includes(kind as (typeof ADMIN_REPORTS)[number]["key"]);
  if (isAdminReport && actor.role !== "admin") return null;
  if (!isAdminReport && !CUSTOMER_REPORTS.some((report) => report.key === kind)) return null;

  const dataset = isAdminReport ? await adminDataset(actor, kind) : await customerDataset(actor, kind);
  if (!dataset) return null;

  if (format === "csv") {
    return { dataset, contentType: "text/csv; charset=utf-8", body: toCsv(dataset), extension: "csv" };
  }
  return { dataset, contentType: "application/pdf", body: datasetToPdf(dataset), extension: "pdf" };
}

async function customerDataset(
  actor: { id: string; full_name: string; email: string },
  kind: string,
): Promise<Dataset | null> {
  const sql = getSql();
  const subtitle = `${actor.full_name} · ${actor.email} · generated ${new Date().toISOString().slice(0, 10)}`;

  if (kind === "account_statement") {
    const found = rows<Record<string, unknown>>(await sql`
      SELECT a.account_number, a.account_type, trim(a.currency) AS currency, a.status,
             a.created_at::text AS created_at,
             COALESCE((SELECT sum(e.amount) FROM ledger_entries e WHERE e.account_id = a.id), 0)::text AS balance
      FROM customer_accounts a WHERE a.user_id = ${actor.id} ORDER BY a.created_at DESC
    `);
    return {
      title: "Account statement",
      subtitle,
      columns: [
        { key: "account_number", label: "Account" },
        { key: "account_type", label: "Type" },
        { key: "currency", label: "Currency" },
        { key: "status", label: "Status" },
        { key: "balance", label: "Balance" },
        { key: "created_at", label: "Opened" },
      ],
      rows: found.map((row) => ({
        account_number: String(row.account_number ?? "—"),
        account_type: String(row.account_type),
        currency: String(row.currency).trim(),
        status: String(row.status),
        balance: String(row.balance),
        created_at: String(row.created_at).slice(0, 10),
      })),
    };
  }

  if (kind === "investment_statement") {
    const found = rows<Record<string, unknown>>(await sql`
      SELECT p.name, i.principal::text AS principal, trim(i.currency) AS currency, i.status,
             p.risk_level, p.duration_days, i.created_at::text AS created_at
      FROM investments i JOIN investment_products p ON p.id = i.product_id
      WHERE i.user_id = ${actor.id} ORDER BY i.created_at DESC
    `);
    return {
      title: "Investment statement",
      subtitle,
      columns: [
        { key: "name", label: "Product" },
        { key: "principal", label: "Principal" },
        { key: "currency", label: "Currency" },
        { key: "status", label: "Status" },
        { key: "risk_level", label: "Risk" },
        { key: "duration_days", label: "Term (days)" },
        { key: "created_at", label: "Requested" },
      ],
      rows: found.map((row) => ({
        name: String(row.name),
        principal: String(row.principal),
        currency: String(row.currency).trim(),
        status: String(row.status),
        risk_level: String(row.risk_level),
        duration_days: row.duration_days === null ? "Open-ended" : String(row.duration_days),
        created_at: String(row.created_at).slice(0, 10),
      })),
    };
  }

  if (kind === "transactions" || kind === "deposits" || kind === "withdrawals") {
    const found = rows<Record<string, unknown>>(await sql`
      SELECT t.reference, t.description, e.amount::text AS amount, trim(e.currency) AS currency,
             t.status, e.created_at::text AS created_at,
             COALESCE(w.wallet_number, a.account_number) AS owner
      FROM ledger_entries e
      JOIN ledger_transactions t ON t.id = e.transaction_id
      LEFT JOIN wallets w ON w.id = e.wallet_id
      LEFT JOIN customer_accounts a ON a.id = e.account_id
      WHERE (w.user_id = ${actor.id} OR a.user_id = ${actor.id})
        AND (${kind}::text = 'transactions'
             OR (${kind}::text = 'deposits' AND COALESCE(t.reference,'') LIKE 'DEP-%')
             OR (${kind}::text = 'withdrawals' AND COALESCE(t.reference,'') LIKE 'WDR-%'))
      ORDER BY e.created_at DESC LIMIT 2000
    `);
    return {
      title: kind === "transactions" ? "Transaction report" : kind === "deposits" ? "Deposit report" : "Withdrawal report",
      subtitle,
      columns: [
        { key: "created_at", label: "Date" },
        { key: "reference", label: "Reference" },
        { key: "description", label: "Description" },
        { key: "owner", label: "Account" },
        { key: "amount", label: "Amount" },
        { key: "currency", label: "Currency" },
        { key: "status", label: "Status" },
      ],
      rows: found.map((row) => ({
        created_at: String(row.created_at).slice(0, 16).replace("T", " "),
        reference: String(row.reference ?? "—"),
        description: String(row.description),
        owner: String(row.owner ?? "—"),
        amount: String(row.amount),
        currency: String(row.currency).trim(),
        status: String(row.status),
      })),
    };
  }

  if (kind === "portfolio_performance") {
    const found = rows<Record<string, unknown>>(await sql`
      SELECT as_of::text AS as_of, total_value::text AS total_value, invested_value::text AS invested_value,
             cash_value::text AS cash_value, returns_value::text AS returns_value,
             trim(currency) AS currency, is_demo
      FROM portfolio_snapshots WHERE user_id = ${actor.id} ORDER BY as_of ASC LIMIT 400
    `);
    return {
      title: "Portfolio performance",
      subtitle,
      columns: [
        { key: "as_of", label: "Date" },
        { key: "total_value", label: "Total value" },
        { key: "invested_value", label: "Invested" },
        { key: "cash_value", label: "Cash" },
        { key: "returns_value", label: "Unrealised" },
        { key: "currency", label: "Currency" },
        { key: "demo", label: "Data" },
      ],
      rows: found.map((row) => ({
        as_of: String(row.as_of),
        total_value: String(row.total_value),
        invested_value: String(row.invested_value),
        cash_value: String(row.cash_value),
        returns_value: String(row.returns_value),
        currency: String(row.currency).trim(),
        demo: row.is_demo ? "Simulated" : "Actual",
      })),
    };
  }

  return null;
}

async function adminDataset(
  actor: { id: string; full_name: string; email: string },
  kind: string,
): Promise<Dataset | null> {
  const sql = getSql();
  const subtitle = `Generated by ${actor.full_name} (${actor.email}) · ${new Date().toISOString().slice(0, 16).replace("T", " ")}`;

  if (kind === "admin_activity") {
    const found = rows<Record<string, unknown>>(await sql`
      SELECT e.action, e.entity_type, e.entity_id, e.created_at::text AS created_at, u.email AS actor_email
      FROM audit_events e LEFT JOIN app_users u ON u.id = e.actor_user_id
      ORDER BY e.created_at DESC LIMIT 2000
    `);
    return {
      title: "Administrative activity",
      subtitle,
      columns: [
        { key: "created_at", label: "When" },
        { key: "action", label: "Action" },
        { key: "entity_type", label: "Entity" },
        { key: "entity_id", label: "Entity ID" },
        { key: "actor_email", label: "Actor" },
      ],
      rows: found.map((row) => ({
        created_at: String(row.created_at).slice(0, 16).replace("T", " "),
        action: String(row.action),
        entity_type: String(row.entity_type),
        entity_id: String(row.entity_id ?? "—"),
        actor_email: String(row.actor_email ?? "system"),
      })),
    };
  }

  if (kind === "compliance") {
    const found = rows<Record<string, unknown>>(await sql`
      SELECT u.full_name, u.email, u.status AS account_status,
             COALESCE(k.status, 'not_submitted') AS kyc_status, COALESCE(k.risk_rating, '—') AS risk_rating,
             k.submitted_at::text AS submitted_at, k.reviewed_at::text AS reviewed_at,
             k.rejection_reason
      FROM app_users u LEFT JOIN kyc_submissions k ON k.user_id = u.id
      WHERE u.role = 'customer'
      ORDER BY CASE WHEN k.status = 'pending' THEN 0 ELSE 1 END, u.created_at DESC
      LIMIT 2000
    `);
    return {
      title: "Compliance report",
      subtitle,
      columns: [
        { key: "full_name", label: "Customer" },
        { key: "email", label: "Email" },
        { key: "account_status", label: "Account" },
        { key: "kyc_status", label: "KYC" },
        { key: "risk_rating", label: "Risk" },
        { key: "submitted_at", label: "Submitted" },
        { key: "reviewed_at", label: "Reviewed" },
        { key: "rejection_reason", label: "Reason" },
      ],
      rows: found.map((row) => ({
        full_name: String(row.full_name),
        email: String(row.email),
        account_status: String(row.account_status),
        kyc_status: String(row.kyc_status),
        risk_rating: String(row.risk_rating),
        submitted_at: String(row.submitted_at ?? "—").slice(0, 10),
        reviewed_at: String(row.reviewed_at ?? "—").slice(0, 10),
        rejection_reason: String(row.rejection_reason ?? ""),
      })),
    };
  }

  return null;
}
